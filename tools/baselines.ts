// Leader baselines (spec 07): how often a level-appropriate party wins each room type at each
// HP level, and what it costs. Leaders of Veteran rank and above plan with this table.
// Regenerate with `npm run baselines` after balance changes.
import { writeFileSync } from 'node:fs';
import { buildEncounter } from '../src/sim/encounter';
import { runFight } from '../src/sim/fight';
import { party, PRESETS } from '../src/sim/presets';
import { stream } from '../src/sim/rng';
import { TIERS } from '../src/sim/data';
import type { RoomType } from '../src/sim/types';

const HP = [0.3, 0.5, 0.7, 0.9, 1.0];
const ROOMS: RoomType[] = ['normal', 'elite', 'horde', 'boss'];
const N = 40;
const out: Record<string, Record<string, { hp: number; win: number; hpCost: number; deaths: number }[]>> = {};
for (const tier of Object.keys(TIERS)) {
  out[tier] = {};
  for (const room of ROOMS) {
    out[tier][room] = [];
    for (const hp of HP) {
      let win = 0, cost = 0, deaths = 0;
      for (let s = 0; s < N; s++) {
        const heroes = party(PRESETS.starter, tier);
        const full = heroes.map((h) => ({ ...h }));
        const r0 = runFight({ seed: s, key: ['base0', tier, room], tier, roomType: room, heroes: full, monsters: [], maxTime: 0.05 });
        const max = new Map(r0.units.map((u) => [u.id, u.maxHp]));
        const r = runFight({ seed: s, key: ['base', tier, room, hp], tier, roomType: room, heroes: heroes.map((h) => ({ ...h, hp: Math.round((max.get(h.id) ?? 100) * hp) })), monsters: buildEncounter(tier, room, TIERS[tier].floors[0] + 1, stream(s, 'base-enc', tier, room)) });
        if (r.result === 'victory') win++;
        const hs = r.units.filter((u) => u.kind === 'hero');
        cost += Math.max(0, hp - hs.reduce((a, u) => a + u.hp / u.maxHp, 0) / hs.length);
        deaths += r.died.length / hs.length;
      }
      out[tier][room].push({ hp, win: +(win / N).toFixed(3), hpCost: +(cost / N).toFixed(3), deaths: +(deaths / N).toFixed(3) });
    }
  }
}
writeFileSync('data/leader-baselines.json', JSON.stringify({ _doc: 'Generated by npm run baselines (tools/baselines.ts). Win rate, HP cost and per-hero death rate by tier, room and entering party HP.', table: out }, null, 1) + '\n');
console.log(JSON.stringify(out.II));
